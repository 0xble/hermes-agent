"""Deliver keyed host notices once without changing tool results or frozen history.

Install/update and other host callers share the existing queue. The next model
continuation after a tool batch drains it into a new user-role runtime notice,
combined with a concurrent steer before either is persisted. With no tool
continuation, the next user turn still carries the queued notices.
"""

from __future__ import annotations

import threading
from typing import Any

_QUEUED = "_plugin_live_notes"
# Producer-owned replay provenance, persisted in display_metadata, never on the wire.
RUNTIME_NOTICE = "runtime_notice"
RUNTIME_NOTICE_TEMPLATE = (
    "[HERMES RUNTIME NOTICE: generated by the host, not a user message or tool output]\n"
    "{notes}\n[/HERMES RUNTIME NOTICE]"
)
# The install RPC thread queues while the agent thread delivers.
_LOCK = threading.Lock()


def _queued(agent: Any) -> dict[str, str]:
    notes = getattr(agent, _QUEUED, None)
    return notes if isinstance(notes, dict) else {}


def queue_plugin_notice(agent: Any, plugin_key: str, note: str) -> None:
    """Queue a notice for the next continuation or user turn, replacing this key's older one."""
    with _LOCK:
        notes = {key: text for key, text in _queued(agent).items() if key != plugin_key}
        notes[plugin_key] = note
        setattr(agent, _QUEUED, notes)


def pop_plugin_notices(agent: Any) -> str:
    """Every queued notice, oldest plugin first, and clear the queue."""
    with _LOCK:
        notes = _queued(agent)
        if notes:
            setattr(agent, _QUEUED, {})
    return "\n\n".join(notes.values())


def is_runtime_notice(message: Any) -> bool:
    """Producer provenance identifying an unstamped host-notice continuation row."""
    metadata = message.get("display_metadata") if isinstance(message, dict) else None
    return isinstance(metadata, dict) and metadata.get(RUNTIME_NOTICE) is True


def with_plugin_notices(agent: Any, row: dict[str, Any]) -> dict[str, Any]:
    """Frame queued host text on a NEW user row before its first append or persistence."""
    notes = pop_plugin_notices(agent)
    if not notes:
        return row
    prefix = RUNTIME_NOTICE_TEMPLATE.format(notes=notes)
    content = row.get("content") or ""
    combined = {**row, "content": f"{prefix}\n\n{content}" if content else prefix,
                "display_metadata": {**row.get("display_metadata", {}), RUNTIME_NOTICE: True}}
    if isinstance(row.get("api_content"), str):
        combined["api_content"] = f"{prefix}\n\n{row['api_content']}"
    return combined


def append_redirect_correction(agent: Any, messages: list[dict], text: str, checkpoint: str) -> None:
    """Compose pending controls before the redirect's fresh correction is persisted.

    The prior request may already end in a steer/notice row. Folding guidance
    into the new correction preserves chronology without inserting into history.
    Host framing stays separate from human authority in both transcript and replay.
    """
    from agent.message_metadata import append_message
    from agent.steer_delivery import report_steer_delivered

    steer_text = agent._drain_pending_steer()
    human_text = f"{steer_text}\n\n{text}" if steer_text else text
    correction = f"[Context from the interrupted assistant response]\n{checkpoint}\n\n{human_text}"
    row = with_plugin_notices(agent, {"role": "user", "content": human_text, "api_content": correction})
    append_message(messages, row)
    if steer_text:
        report_steer_delivered(agent, steer_text)


def append_continuation_notice(agent: Any, messages: list[dict], steer_text: str | None = None) -> bool:
    """Drain only after a complete tool batch, at the pre-request boundary.

    A separate row preserves every result byte, including JSON and multimodal
    parts. Combining an optional steer in this NEW row avoids a later
    consecutive-user repair rewriting an already flushed notice or steer.
    Generated compression scaffolding may follow the batch, but human intent
    still owns its next request. False leaves controls queued for the caller.
    """
    if not messages:
        return False
    tail_role = messages[-1].get("role")
    if tail_role != "tool":
        from agent.context_compressor import user_originated_turn_view
        from agent.message_metadata import INFLIGHT_TASK_RESTATEMENT

        # A standalone compressor replay retains human authority, but is not
        # new inbound input. Only its producer flag authorizes this exception,
        # never pasted header text or a handoff carrying a new human request.
        metadata = messages[-1].get("display_metadata")
        restatement = isinstance(metadata, dict) and metadata.get(INFLIGHT_TASK_RESTATEMENT) is True
        if tail_role != "user" or (not restatement and user_originated_turn_view(messages[-1]) is not None):
            return False
    from agent.prompt_builder import steer_user_row

    row = steer_user_row(steer_text) if steer_text else {
        "role": "user", "content": "", "display_kind": "internal_notification"}
    row = with_plugin_notices(agent, row)
    if not row["content"]:
        return False
    if tail_role == "user":
        from agent.agent_runtime_helpers_placeholders import hidden_interrupt_placeholder_row

        messages.append(hidden_interrupt_placeholder_row())
    messages.append(row)
    if steer_text:
        from agent.steer_delivery import report_steer_delivered
        report_steer_delivered(agent, steer_text)
    return True

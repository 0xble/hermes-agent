"""Git plumbing: which files changed between two trees, and their contents on either side.

A tree is a revision (``"abc123"``) or ``None`` for the working tree. Both sides are read
through the same functions so base and head are measured identically.
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from pathlib import Path

from hermes_agent.compat.paths import PathMoves, moves_from_source


def git(repo: Path, *args: str, check: bool = True) -> str:
    proc = subprocess.run(
        ["git", *args],
        cwd=repo,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        stdin=subprocess.DEVNULL,
        timeout=120,
        check=False,
    )
    if check and proc.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc.stdout


def repo_root(start: Path) -> Path:
    return Path(git(start, "rev-parse", "--show-toplevel").strip())


def resolve_rev(repo: Path, rev: str) -> str:
    return git(repo, "rev-parse", "--verify", f"{rev}^{{commit}}").strip()


def resolve_tree(repo: Path, rev: str) -> str:
    """A head may be any tree-ish: a commit, or the index's tree from ``git write-tree``."""
    return git(repo, "rev-parse", "--verify", f"{rev}^{{tree}}").strip()


def commit_or_none(repo: Path, rev: str) -> str | None:
    """``rev`` as a commit sha, or None when it does not name a commit (a tree, a missing ref)."""
    out = git(repo, "rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}", check=False)
    return out.strip() or None


def default_base(repo: Path, tip: str = "HEAD") -> str:
    """Merge-base of ``tip`` with origin/main (local runs); CI passes ``--base`` explicitly."""
    for ref in ("origin/main", "main"):
        out = git(repo, "merge-base", tip, ref, check=False).strip()
        if out:
            return out
    raise RuntimeError("no merge-base with origin/main or main; pass --base")


@dataclass(frozen=True)
class Change:
    status: str  # A, M, D, R
    old: str | None
    new: str | None


def _parse_name_status(out: str) -> list[Change]:
    fields = out.split("\0")
    changes: list[Change] = []
    i = 0
    while i < len(fields) and fields[i]:
        code = fields[i][0]
        if code in "RC":
            old, new = fields[i + 1], fields[i + 2]
            changes.append(Change("R" if code == "R" else "A", old if code == "R" else None, new))
            i += 3
            continue
        path = fields[i + 1]
        if code == "D":
            changes.append(Change("D", path, None))
        elif code == "A":
            changes.append(Change("A", None, path))
        else:
            changes.append(Change("M", path, path))
        i += 2
    return changes


MOVES_FILE = "hermes_agent/compat/moves.py"
GENERATED_BLOCK = ("# BEGIN shims (generated by scripts/move/generate_shims.py; do not edit)\n", "# END shims\n")


def generated_files(repo: Path, tree: str | None) -> set[str]:
    """Paths ``scripts/move/generate_shims.py`` writes, as the ``.gitattributes`` of ``tree`` lists them.

    They are generated old-path files (shims and byte copies of moved files), not code anyone wrote
    in this change, so they are not judged.
    """
    text = read_file(repo, tree, ".gitattributes") or ""
    block = text.partition(GENERATED_BLOCK[0])[2].partition(GENERATED_BLOCK[1])[0]
    return {line.split()[0].removeprefix("/") for line in block.splitlines() if line.strip()}


def tree_moves(repo: Path, tree: str | None) -> dict[str, str]:
    """The ``MOVES`` table as ``tree`` holds it (old module name -> current name)."""
    return moves_from_source(read_file(repo, tree, MOVES_FILE))


def _pair_moves(changes: list[Change], original, base_files: set[str]) -> list[Change]:
    """Pair each new file with the base file the head's ``MOVES`` says it was.

    A move leaves a generated file at the old path, so git sees an add plus a modify and never pairs
    them. A file that existed on the base keeps its own path; the file left behind reads as new.
    """
    pairs = {c.new: original(c.new) for c in changes
             if c.new is not None and c.status != "M" and original(c.new) != c.new
             and original(c.new) in base_files and c.old != original(c.new)}
    if not pairs:
        return changes
    claimed = set(pairs.values())
    paired: list[Change] = []
    for c in changes:
        if c.new in pairs:
            paired.append(Change("R", pairs[c.new], c.new))
            if c.old is not None and c.old not in claimed:
                paired.append(Change("D", c.old, None))
        elif c.old in claimed:
            if c.new is not None:
                paired.append(Change("A", None, c.new))
        else:
            paired.append(c)
    return paired


def changed_files(repo: Path, base: str, head: str | None, *diff_args: str) -> list[Change]:
    args = ["diff", "--name-status", "-M", *diff_args, "-z", "--no-color", base]
    if head is not None:
        args.append(head)
    changes = _parse_name_status(git(repo, *args))
    if head is None:
        untracked = git(repo, "ls-files", "--others", "--exclude-standard", "-z")
        changes.extend(Change("A", None, p) for p in untracked.split("\0") if p)
    moves = tree_moves(repo, head)
    if moves:
        changes = _pair_moves(changes, PathMoves(moves).original,
                              set(tracked_files(repo, base)) - generated_files(repo, base))
    generated = generated_files(repo, head)
    return [c for c in changes if c.new not in generated]


def _read_files_individually(repo: Path, tree: str | None, paths: list[str]) -> dict[str, str]:
    contents = {}
    for path in paths:
        text = read_file(repo, tree, path)
        if text is not None:
            contents[path] = text
    return contents


def read_files(repo: Path, tree: str | None, paths: list[str]) -> dict[str, str]:
    """Read committed paths with one Git object-stream process.

    Code-health compares thousands of paths on a large sync. Spawning ``git show`` once per
    path makes that comparison take hours, while ``cat-file --batch`` returns the same blobs
    through one bounded subprocess. Unusual paths or a malformed batch response use the old
    per-path reader so the batch optimization cannot change the read contract.
    """
    selected = [path for path in paths if path]
    if not selected or tree is None:
        return _read_files_individually(repo, tree, selected)
    if any("\n" in path or "\r" in path for path in selected):
        return _read_files_individually(repo, tree, selected)
    request = b"".join(f"{tree}:{path}\n".encode("utf-8") for path in selected)
    try:
        proc = subprocess.run(
            ["git", "cat-file", "--batch"],
            cwd=repo,
            input=request,
            capture_output=True,
            timeout=120,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return _read_files_individually(repo, tree, selected)
    if proc.returncode != 0:
        return _read_files_individually(repo, tree, selected)

    contents: dict[str, str] = {}
    cursor = 0
    for path in selected:
        header_end = proc.stdout.find(b"\n", cursor)
        if header_end < 0:
            return _read_files_individually(repo, tree, selected)
        header = proc.stdout[cursor:header_end].split()
        cursor = header_end + 1
        if header and header[-1] == b"missing":
            continue
        if len(header) < 3 or header[-2] != b"blob":
            return _read_files_individually(repo, tree, selected)
        try:
            size = int(header[-1])
        except ValueError:
            return _read_files_individually(repo, tree, selected)
        end = cursor + size
        if end >= len(proc.stdout) or proc.stdout[end:end + 1] != b"\n":
            return _read_files_individually(repo, tree, selected)
        contents[path] = proc.stdout[cursor:end].decode("utf-8-sig", errors="replace")
        cursor = end + 1
    return contents


def prefetch_blobs(repo: Path, tree: str, paths: list[str]) -> None:
    """Hydrate a blobless clone's missing blobs for ``paths`` in one fetch.

    Without this, each ``git show`` below lazily fetches its own blob and leaves one
    promisor pack per file in the shared object store. Any failure here only loses
    the batching: the per-file reads still fetch what they need.
    """
    if not paths:
        return
    try:
        _prefetch_missing(repo, tree, paths)
    except (subprocess.TimeoutExpired, OSError):
        pass  # only batching is lost; read_file still fetches and reports each blob itself


def _prefetch_missing(repo: Path, tree: str, paths: list[str]) -> None:
    if not git(repo, "config", "--get", "remote.origin.partialclonefilter", check=False).strip():
        return
    # rev-list --missing=print names absent blobs ("?<oid>") without lazily fetching them,
    # on every git version (GIT_NO_LAZY_FETCH only exists from 2.45; CI ships older git).
    # Walk the tree object, not the commit: a commit walk with paths skips untouched commits.
    listing = git(repo, "--literal-pathspecs", "rev-list", "--objects", "--no-walk", "--missing=print",
                  f"{tree}^{{tree}}", "--", *paths, check=False)
    missing = [line[1:] for line in listing.splitlines() if line.startswith("?")]
    if missing:
        subprocess.run(  # same single-fetch pattern as scripts/ci/prefetch_tree.py
            ["git", "-c", "fetch.negotiationAlgorithm=noop", "fetch", "--no-tags", "--no-write-fetch-head",
             "--recurse-submodules=no", "--filter=blob:none", "--stdin", "origin"],
            cwd=repo, input="\n".join(missing) + "\n", capture_output=True, text=True, timeout=120,
            check=False,
        )


def read_file(repo: Path, tree: str | None, path: str) -> str | None:
    if tree is None:
        try:
            return (repo / path).read_text(encoding="utf-8-sig", errors="replace")
        except (FileNotFoundError, IsADirectoryError):
            return None
    proc = subprocess.run(
        ["git", "show", f"{tree}:{path}"],
        cwd=repo,
        capture_output=True,
        stdin=subprocess.DEVNULL,
        timeout=60,
        check=False,
    )
    if proc.returncode != 0:
        return None
    # Same decoding as the working-tree read: a BOM must not make the two sides disagree.
    return proc.stdout.decode("utf-8-sig", errors="replace")


def tracked_files(repo: Path, tree: str | None) -> list[str]:
    if tree is None:
        return [p for p in git(repo, "ls-files", "-z").split("\0") if p]
    return [p for p in git(repo, "ls-tree", "-r", "--name-only", "-z", tree).split("\0") if p]


def known_env_names(repo: Path, tree: str | None) -> set[str]:
    """Every HERMES_* literal in non-test Python of a tree (the HX002 allow set)."""
    args = ["grep", "-h", "-o", "-I", "-E", r"HERMES_[A-Z0-9_]+"]
    if tree is not None:
        args.append(tree)
    args += ["--", "*.py", ":!tests/**", ":!**/tests/**"]
    out = git(repo, *args, check=False)
    names = set()
    for line in out.splitlines():
        # `git grep <tree>` prefixes "<tree>:" even with -h on some versions.
        names.add(line.rsplit(":", 1)[-1])
    return names
